sectionSelect.addEventListener("change", function () {

    const selectedSection = this.value;


    // Clear old chapters

    chapterSelect.innerHTML =
        '<option value="">-- ಅಧ್ಯಾಯ ಆಯ್ಕೆಮಾಡಿ --</option>';


    // Clear description

    description.innerHTML =
        "ಅಧ್ಯಾಯವನ್ನು ಆಯ್ಕೆ ಮಾಡಿದ ನಂತರ ವಿವರಣೆ ಇಲ್ಲಿ ಕಾಣಿಸುತ್ತದೆ.";


    // Nothing selected

    if (selectedSection === "") {

        chapterSelect.disabled = true;

        return;
    }


    // Enable chapter dropdown

    chapterSelect.disabled = false;


    // Get chapters

    const chapters = data[selectedSection].chapters;


    // Add chapters

    chapters.forEach(function (chapter, index) {

        const option = document.createElement("option");

        option.value = index;

        option.textContent = chapter.name;

        chapterSelect.appendChild(option);

    });

});



// ==========================================
// FORMAT DESCRIPTION TEXT AUTOMATICALLY
// ==========================================

function formatDescription(html, chapterName) {
    const wrapper = document.createElement("div");
    wrapper.innerHTML = html;

    // Add chapter title
    const title = document.createElement("div");
    title.className = "chapter-title";
    title.textContent = chapterName;
    wrapper.insertBefore(title, wrapper.firstChild);

    // Convert plain text lines into styled paragraphs
    Array.from(wrapper.childNodes).forEach(function (node) {
        if (node.nodeType === Node.TEXT_NODE && node.textContent.trim() !== "") {
            const text = node.textContent.trim();

            const p = document.createElement("p");
            p.className = text.includes(":-") && text.length < 100
                ? "heading"
                : "meaning";
            p.textContent = text;

            node.parentNode.replaceChild(p, node);
        }
    });

    // Automatically style existing <p> passages
    wrapper.querySelectorAll("p").forEach(function (p) {
        const text = p.textContent.trim();

        // Headings such as "ದೋಷಗಳು:-", "ಪ್ರಕೃತಿ:-", etc.
        if (text.includes(":-") && text.length < 100) {
            p.className = "heading";
            return;
        }

        // Short Sanskrit/original verses normally contain | or ||
        // and are much shorter than explanatory paragraphs.
        if ((text.includes("||") || text.includes("|")) && text.length < 180) {
            p.className = "verse";
        } else {
            p.className = "meaning";
        }
    });

    return wrapper.innerHTML;
}


